/*
# 다형성
- 정의: 하나의 형태(부모 타입 참조 변수 또는 인터페이스)가 여러 가지 서로 다른 형태(자식 객체들)로 변할 수 있는 객체지향의 특성.
- 의미:
    부모 클래스 타입의 변수 하나로 여러 자식 클래스의 인스턴스를 가리킬 수 있으며,
    동일한 메서드 호출 메시지를 보내더라도 각 객체의 실제 타입에 따라 서로 다르게 동작하는 것을 말함.

# 오버라이딩과 다형성의 관계
- 관계: 오버라이딩(Overriding)은 다형성을 구현하는 핵심 수단(메커니즘)임.
- 설명:
    기반 클래스에서 정의한 가상 메서드(virtual)를 파생 클래스에서 오버라이딩(override)하여 재정의해 두면,
    부모 타입으로 메서드를 호출했을 때 실제 할당된 자식 객체의 오버라이딩된 메서드가 호출되어 다형성이 완성됨.
*/